"""v1.0 → v1.5.1 vault migration: plan / apply / verify / rollback.

- `plan` is strictly read-only: inventories the live vault (never assumes a
  file count), parses every note with the real YAML layer, generates stable IDs
  without changing content, maps old MOCs to the new taxonomy, and detects
  basename collisions and malformed frontmatter. Emits per-file planned
  changes to $KF_STATE_HOME/migration/plan.json + a Markdown report.
- `apply` executes the plan against a STAGED FULL COPY of the vault by default
  (`--live` applies to the real vault only after a plan exists, a verified
  backup exists, and --approved-by is given). Source note bodies are never
  modified; identity frontmatter is added through reversible edits (original
  file preserved in the transaction backup + a pre-migration checkpoint).
- `verify` compares source counts, URLs, content hashes and attachments
  between pre- and post-migration states.
- `rollback` restores the pre-migration checkpoint.
"""
