# v1.0 tag → v1.5.1 category mapping (from vault/90_meta/taxonomy.md)
V1_TAG_TO_CATEGORY = {
    "ai-governance": "cat_ai_governance",
    "llm-eng": "cat_ai_llm_eng",
    "quant-risk": "cat_quant_risk",
    "political-economy": "cat_political_economy",
    "history": "cat_history",
    "music": "cat_music",
    "术数": "cat_shushu",
    "method": "cat_method",
}
V1_GENERATED = {"HOME.md", "🏠 HOME.md", "40_maps/_Dashboard.md",
                "40_maps/_Knowledge Map.md", "90_meta/index.md",
                "90_meta/provenance.md"}


def _mig_dir(cfg: KFConfig) -> Path:
    d = cfg.state_home / "migration"
    d.mkdir(parents=True, exist_ok=True)
    return d


def plan(cfg: KFConfig, vault: Optional[Path] = None) -> dict:
    vault = vault or cfg.vault
    vi = VaultIndex.build(vault)
    body_hash_seen: dict[str, str] = {}
    per_file, collisions, malformed = [], [], []
    stats = {"total_notes": 0, "sources": 0, "already_v151": 0,
             "need_id": 0, "generated_to_replace": 0, "duplicates": 0}

    for n in vi.notes:
        r = rel(vault, n.path) + ".md"
        stats["total_notes"] += 1
        if n.parse_error:
            malformed.append({"path": r, "error": n.parse_error,
                              "action": "quarantine_frontmatter_repair"})
            continue
        if r in V1_GENERATED or n.path.name.startswith("_") and "40_maps" in r:
            stats["generated_to_replace"] += 1
            per_file.append({"path": r, "action": "replace_generated",
                             "detail": "v1.0 navigation artifact → regenerated by v1.5.1"})
            continue
        t = n.meta.get("note_type") or n.meta.get("type")
        if n.meta.get("id") and n.meta.get("schema_version") == "1.5.1":
            stats["already_v151"] += 1
            per_file.append({"path": r, "action": "keep"})
            continue
        changes = {}
        if not n.meta.get("id"):
            stats["need_id"] += 1
            if t == "source":
                canonical = n.meta.get("canonical_url") or n.meta.get("url")
                chash = n.meta.get("content_hash") or ids.content_sha256(n.body)
                nid = ids.source_id(canonical, chash)
                if nid in body_hash_seen:
                    stats["duplicates"] += 1
                    per_file.append({"path": r, "action": "flag_duplicate",
                                     "duplicate_of": body_hash_seen[nid]})
                    continue
                body_hash_seen[nid] = r
            else:
                nid = ids.note_id(t or "note")
            changes["id"] = nid
        if t == "source":
            stats["sources"] += 1
            changes.setdefault("note_type", "source")
            changes.setdefault("capture_status",
                               n.meta.get("capture_status") or "complete")
            changes.setdefault("capture_method", n.meta.get("capture_method") or "manual")
            changes.setdefault("content_completeness",
                               n.meta.get("content_completeness", 0.9))
            if not n.meta.get("content_hash"):
                changes["content_hash"] = ids.content_sha256(n.body)
        else:
            changes.setdefault("note_type", t or "concept")
        # tag → category proposal
        cat = None
        for tag in (n.meta.get("tags") or []):
            if tag in V1_TAG_TO_CATEGORY:
                cat = V1_TAG_TO_CATEGORY[tag]
                break
        if cat and not n.meta.get("primary_category_id"):
            changes["primary_category_id"] = cat
        changes["schema_version"] = "1.5.1"
        per_file.append({"path": r, "action": "add_identity_frontmatter",
                         "changes": changes,
                         "category_mapping": cat, "body_modified": False})

    # basename collisions across dirs (v1.0 link hazard)
    for stem, rels in vi.by_basename.items():
        if len(rels) > 1:
            collisions.append({"basename": stem, "paths": rels})

    p = {
        "generated_at": dt.datetime.now().astimezone().isoformat(timespec="seconds"),
        "vault": str(vault),
        "stats": stats,
        "per_file": per_file,
        "basename_collisions": collisions,
        "malformed_frontmatter": malformed,
        "unresolved": [c for c in collisions],
        "note": "dry run — the live vault was not modified",
    }
    (_mig_dir(cfg) / "plan.json").write_text(json.dumps(p, ensure_ascii=False, indent=1),
                                             encoding="utf-8")
    (_mig_dir(cfg) / "plan.md").write_text(render_plan_md(p), encoding="utf-8")
    return p


def render_plan_md(p: dict) -> str:
    s = p["stats"]
    L = [f"# Migration dry-run report — {p['generated_at']}", "",
         f"Vault: `{p['vault']}`", "",
         "## Summary",
         f"- Notes inventoried: **{s['total_notes']}** (live count — not assumed)",
         f"- Source notes: {s['sources']}",
         f"- Need stable IDs: {s['need_id']}",
         f"- Already v1.5.1: {s['already_v151']}",
         f"- Generated v1.0 navigation to replace: {s['generated_to_replace']}",
         f"- Duplicate sources flagged: {s['duplicates']}",
         f"- Basename collisions: {len(p['basename_collisions'])}",
         f"- Malformed frontmatter: {len(p['malformed_frontmatter'])}", "",
         "## Per-file planned changes", ""]
    for f_ in p["per_file"]:
        det = ""
        if f_.get("changes"):
            det = " → sets " + ", ".join(f"{k}" for k in f_["changes"])
        if f_.get("category_mapping"):
            det += f" · category {f_['category_mapping']}"
        L.append(f"- `{f_['path']}` — {f_['action']}{det}")
    if p["basename_collisions"]:
        L += ["", "## ⚠️ Basename collisions (links will be repointed to full paths)"]
        L += [f"- `{c['basename']}` → {c['paths']}" for c in p["basename_collisions"]]
    if p["malformed_frontmatter"]:
        L += ["", "## ⚠️ Malformed frontmatter (quarantined for repair)"]
        L += [f"- `{m['path']}`: {m['error']}" for m in p["malformed_frontmatter"]]
    L += ["", "> Dry run only. Apply with `kf migrate apply` (staged copy) then "
          "`kf migrate apply --live --approved-by liang` after review."]
    return "\n".join(L) + "\n"


def apply(cfg: KFConfig, live: bool = False, approved_by: Optional[str] = None) -> dict:
    ppath = _mig_dir(cfg) / "plan.json"
    if not ppath.exists():
        return {"ok": False, "error": "no plan found — run `kf migrate plan` first"}
    p = json.loads(ppath.read_text(encoding="utf-8"))

    if live:
        if not approved_by:
            return {"ok": False, "error": "live migration requires --approved-by"}
        lb = backup_ops.latest(cfg)
        if not lb:
            return {"ok": False, "error": "no verified backup exists — run `kf backup create` first"}
        target = cfg.vault
        # pre-migration checkpoint for rollback
        checkpoint = _mig_dir(cfg) / "pre_migration_checkpoint"
        if checkpoint.exists():
            shutil.rmtree(checkpoint)
        shutil.copytree(cfg.vault, checkpoint)
    else:
        target = _mig_dir(cfg) / "staged_vault"
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(Path(p["vault"]), target)

    applied, errors = 0, []
    for f_ in p["per_file"]:
        fp = target / f_["path"]
        try:
            if f_["action"] == "add_identity_frontmatter":
                meta, body = fm.read_note(fp)
                meta.update(f_["changes"])
                fp.write_text(fm.dump(meta, body), encoding="utf-8")
                applied += 1
            elif f_["action"] == "replace_generated":
                fp.unlink(missing_ok=True)
                applied += 1
        except Exception as e:
            errors.append(f"{f_['path']}: {type(e).__name__}: {e}")

    # seed taxonomy registry + regenerate navigation on the target
    tcfg = _target_cfg(cfg, target)
    reg = TaxonomyRegistry.load(tcfg.taxonomy_registry_path)
    if not reg.nodes:
        for n in default_registry_nodes():
            reg.nodes[n["category_id"]] = n
    tcfg.taxonomy_registry_path.parent.mkdir(parents=True, exist_ok=True)
    tcfg.taxonomy_registry_path.write_text(reg.dumps(), encoding="utf-8")
    for d in ("80_queues/capture_retry", "80_queues/pending_classification",
              "80_queues/review_required", "60_briefings/daily", "60_briefings/weekly",
              "60_briefings/scripts", "60_briefings/audio", "70_media",
              "90_meta/templates", "90_meta/manifests"):
        (target / d).mkdir(parents=True, exist_ok=True)
    vi = VaultIndex.build(target)
    for relpath, content in generators.rebuild_all(tcfg, vi, reg).items():
        out = target / relpath
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8")
    search.rebuild(tcfg)

    result = {"ok": not errors, "target": str(target), "live": live,
              "applied": applied, "errors": errors}
    (_mig_dir(cfg) / "apply_result.json").write_text(
        json.dumps(result, ensure_ascii=False, indent=1), encoding="utf-8")
    return result


def _target_cfg(cfg: KFConfig, target: Path) -> KFConfig:
    import dataclasses
    return dataclasses.replace(cfg, vault=target)


def verify(cfg: KFConfig) -> dict:
    """Compare original vault vs migrated target: every source URL, content
    hash and attachment must survive."""
    ppath = _mig_dir(cfg) / "plan.json"
    apath = _mig_dir(cfg) / "apply_result.json"
    if not (ppath.exists() and apath.exists()):
        return {"ok": False, "error": "need plan + apply before verify"}
    p = json.loads(ppath.read_text(encoding="utf-8"))
    a = json.loads(apath.read_text(encoding="utf-8"))
    orig, target = Path(p["vault"]), Path(a["target"])

    def collect(root: Path) -> dict:
        out = {}
        for n in iter_notes(root):
            if n.parse_error:
                continue
            t = n.meta.get("note_type") or n.meta.get("type")
            if t == "source":
                key = n.meta.get("canonical_url") or n.meta.get("url") or n.path.stem
                out[key] = {"hash": n.meta.get("content_hash"),
                            "url": n.meta.get("source_url") or n.meta.get("url")}
        return out

    o, t = collect(orig), collect(target) if orig != target else (collect(orig),) * 2
    if orig == target:
        t = o
    missing = [k for k in o if k not in t]
    hash_mismatch = []
    for k in o:
        if k in t and o[k]["hash"] and t[k]["hash"]:
            oh = o[k]["hash"]
            th = t[k]["hash"]
            # allow migration to have ADDED a hash, never changed an existing one
            if oh != th:
                hash_mismatch.append(k)
    # attachments
    oa = sorted(str(x.name) for x in (orig / "_attachments").rglob("*")
                if x.is_file()) if (orig / "_attachments").exists() else []
    ta = sorted(str(x.name) for x in (target / "_attachments").rglob("*")
                if x.is_file()) if (target / "_attachments").exists() else []
    att_missing = [x for x in oa if x not in ta]

    ok = not (missing or hash_mismatch or att_missing)
    return {"ok": ok, "source_count_original": len(o), "source_count_migrated": len(t),
            "missing_sources": missing, "content_hash_mismatches": hash_mismatch,
            "missing_attachments": att_missing}


def rollback(cfg: KFConfig) -> dict:
    checkpoint = _mig_dir(cfg) / "pre_migration_checkpoint"
    if not checkpoint.exists():
        return {"ok": False, "error": "no pre-migration checkpoint exists"}
    trash = _mig_dir(cfg) / f"rolled_back_vault-{dt.datetime.now():%Y%m%d%H%M%S}"
    shutil.move(str(cfg.vault), str(trash))
    shutil.copytree(checkpoint, cfg.vault)
    search.rebuild(cfg)
    return {"ok": True, "restored_from": str(checkpoint),
            "previous_state_kept_at": str(trash)}
