"""Layered navigation generation.

- HOME.md          dashboard only: today's usable captures, review items,
                   pinned/recent domains, recent synthesis, All Domains entry.
                   NO raw source listing, NO folder-scheme explanation.
- Sub-Homes        _index.md for every active L1/L2 (and L3) node.
- Global Atlas     L1+L2 only, bounded (≤40 nodes).
- Domain map       one L1: its L2/L3 descendants + a few synthesis pages.
- Topic map        one topic: children, core concepts, limited related links.
Raw source notes never appear in any map. Output is plain nested Markdown
(+ a small Mermaid block for the Atlas); plugins only enhance display.
All functions RETURN {vault_rel: content}; the caller stages+commits them
through the transaction layer — generators never write directly.
"""
from __future__ import annotations

import datetime as dt
from collections import defaultdict
from typing import Optional

from ..briefing import live as live_brief
from ..config import KFConfig
from ..discovery import VaultIndex, rel
from ..taxonomy.registry import TaxonomyRegistry
from . import brain, desk, library, reading

MAX_ATLAS_NODES = 40
GENERATED_BANNER = "<!-- generated by knowledge-forge; edits will be overwritten -->"


def _today() -> str:
    return dt.date.today().isoformat()


def _fm(title: str, desc: str, extra: str = "") -> str:
    return (f"---\nid: map_{title.lower().replace(' ', '_').replace('/', '_')[:40]}\n"
            f"note_type: map\ntitle: \"{title}\"\ndescription: \"{desc}\"\n"
            f"updated: {_today()}\n{extra}---\n\n{GENERATED_BANNER}\n")


def node_dir(registry: TaxonomyRegistry, cid: str) -> str:
    """Nested 40_maps path for a taxonomy node, e.g. 40_maps/cat_ai/cat_ai_llm_eng."""
    parts = [n["category_id"] for n in registry.path_of(cid)]
    return "40_maps/" + "/".join(parts)


def _notes_by_category(vi: VaultIndex) -> dict:
    by_cat = defaultdict(list)
    for n in vi.notes:
        if n.parse_error:
            continue
        cid = n.meta.get("primary_category_id")
        if cid:
            by_cat[cid].append(n)
        for s in n.meta.get("secondary_category_ids") or []:
            by_cat[s].append(n)
    return by_cat


def _usable(n) -> bool:
    return n.meta.get("capture_status") in (None, "complete", "usable_partial") \
        and n.note_type != "quarantined_capture"


def _descendant_ids(registry: TaxonomyRegistry, cid: str) -> set:
    out, stack = set(), [cid]
    while stack:
        cur = stack.pop()
        out.add(cur)
        stack += [c["category_id"] for c in registry.children(cur)]
    return out


# ---- HOME ------------------------------------------------------------------------------
def build_home(cfg: KFConfig, vi: VaultIndex, registry: TaxonomyRegistry,
               pinned_domains: Optional[list] = None,
               briefing_link: Optional[str] = None,
               audio_link: Optional[str] = None) -> dict:
    today = _today()
    todays, review, recent_synth, recent_domains = [], [], [], []
    for n in vi.notes:
        if n.parse_error:
            continue
        t = n.note_type
        r = rel(cfg.vault, n.path)
        if t == "source" and _usable(n) and str(n.meta.get("captured_at", ""))[:10] == today:
            todays.append((r, n.meta.get("title", n.path.stem)))
        if t != "resolved_capture" and (t == "quarantined_capture" or r.startswith("80_queues/")):
            review.append((r, n.meta.get("title", n.path.stem),
                           n.meta.get("capture_status", "pending")))
        if t == "concept" and str(n.meta.get("updated", "")) >= (
                dt.date.today() - dt.timedelta(days=14)).isoformat():
            recent_synth.append((r, n.meta.get("title", n.path.stem)))
        cid = n.meta.get("primary_category_id")
        if cid and str(n.meta.get("updated", "")) >= (
                dt.date.today() - dt.timedelta(days=14)).isoformat():
            root = registry.path_of(cid)
            if root:
                recent_domains.append(root[0]["category_id"])

    L = [f"# 🏠 HOME", ""]
    L += ["[[LiangWiki Brain.canvas|Open the Brain graph]] · [[Knowledge Map#Expandable branches|Expand topics]]", ""]
    L += ["[[Library Index|Browse the full library]] · [[Library.base#To Review|Reading queue]]", "",
          *desk.home_sections()]
    if (cfg.vault / "90_meta/Library Workflow.md").is_file():
        L += ["[[90_meta/Library Workflow|How the archive is maintained]]", ""]
    L += ["[[Library.base#Recent|Recent sources]] · [[Library.base#By Topic|By topic]] · "
          "[[90_meta/Library Activity|Activity log]]", ""]
    L += [f"> {today} · [[40_maps/_All Domains|📚 All Domains]] · "
          f"[[40_maps/_Global Atlas|🗺 Global Atlas]]", ""]
    if briefing_link:
        L += [f"**今日简报 / Today's briefing:** [[{briefing_link}]]"
              + (f" · 🎧 [[{audio_link}]]" if audio_link else ""), ""]
    L += ["## 今日新增 / New today"]
    L += [f"- [[{r}|{t}]]" for r, t in todays[:10]] or ["- _(nothing captured today)_"]
    if review:
        L += ["", f"## 待处理 / Needs attention ({len(review)})"]
        L += [f"- ⚠️ [[{r}|{t}]] — {s}" for r, t, s in review[:8]]
        if len(review) > 8:
            L.append(f"- …and {len(review) - 8} more in [[Library.base#Needs Attention|Needs Attention]]")
    pinned = pinned_domains or [n["category_id"] for n in registry.active(level=1)][:6]
    L += ["", "## 常用领域 / Pinned domains"]
    for cid in pinned:
        node = registry.get(cid)
        if node:
            L.append(f"- 🗂 [[{node_dir(registry, cid)}/_index|{node['title']}]]")
    active_recent = [c for c in dict.fromkeys(recent_domains) if c not in pinned][:4]
    if active_recent:
        L += ["", "## 最近活跃 / Recently active"]
        for cid in active_recent:
            node = registry.get(cid)
            if node:
                L.append(f"- [[{node_dir(registry, cid)}/_index|{node['title']}]]")
    if recent_synth:
        L += ["", "## 最近更新的综合页 / Recent synthesis"]
        L += [f"- 💡 [[{r}|{t}]]" for r, t in sorted(recent_synth)[:6]]
    L += ["", "## 继续探索 / Continue exploring",
          "- [[40_maps/_All Domains|All Domains]] — 全部知识领域",
          "- 提问示例: 「我关于 X 都收藏过什么？」"]
    content = _fm("HOME", "Dashboard — regenerated; do not hand-edit") + "\n".join(L) + "\n"
    return {"HOME.md": content}


# ---- All Domains + Sub-Homes ---------------------------------------------------------
def build_all_domains(cfg: KFConfig, registry: TaxonomyRegistry) -> dict:
    L = ["# 📚 All Domains", "", brain.navigation(registry, None), ""]
    for l1 in sorted(registry.active(level=1), key=lambda n: n["title"]):
        L.append(f"## [[{node_dir(registry, l1['category_id'])}/_index|{l1['title']}]]")
        if l1.get("description"):
            L.append(f"_{l1['description']}_")
        for l2 in sorted(registry.children(l1["category_id"]), key=lambda n: n["title"]):
            badge = " ⏳" if l2["status"] == "provisional" else ""
            L.append(f"- [[{node_dir(registry, l2['category_id'])}/_index|{l2['title']}]]{badge}")
        L.append("")
    content = _fm("All Domains", "Every knowledge domain — L1/L2 overview") + "\n".join(L)
    return {"40_maps/_All Domains.md": content}


def build_subhomes(cfg: KFConfig, vi: VaultIndex, registry: TaxonomyRegistry) -> dict:
    """_index.md for every active L1/L2/L3 node."""
    by_cat = _notes_by_category(vi)
    out = {}
    for node in registry.active():
        cid = node["category_id"]
        d = node_dir(registry, cid)
        parent_path = registry.path_of(cid)[:-1]
        parent = node_dir(registry, parent_path[-1]["category_id"]) + "/_index" if parent_path else "HOME"
        L = [f"# {node['title']}", "", brain.navigation(registry, cid, include_topic=False),
             "", f"[[{d}/_brain.canvas|Explore this branch in Canvas]]", ""]
        if node.get("description"):
            L += [f"_{node['description']}_", ""]
        kids = sorted(registry.children(cid), key=lambda n: n["title"])
        if kids:
            L.append("## 子类 / Subcategories")
            for k in kids:
                badge = " ⏳provisional" if k["status"] == "provisional" else ""
                L.append(f"- [[{node_dir(registry, k['category_id'])}/_index|{k['title']}]]{badge}")
            L.append("")
        scoped = _descendant_ids(registry, cid)
        here = [n for c in scoped for n in by_cat.get(c, [])]
        concepts = [n for n in here if n.note_type == "concept"][:6]
        if concepts:
            L.append("## 核心综合页 / Core synthesis")
            L += [f"- 💡 [[{rel(cfg.vault, n.path)}|{n.meta.get('title', n.path.stem)}]]"
                  for n in concepts]
            L.append("")
        sources = sorted((n for n in here if n.note_type == "source" and _usable(n)),
                         key=lambda n: str(n.meta.get("captured_at", "")), reverse=True)[:8]
        if sources:
            L.append("## 最近材料 / Recent material")
            L += [f"- [[{rel(cfg.vault, n.path)}|{n.meta.get('title', n.path.stem)}]]"
                  for n in sources]
            L.append("")
        direct = {rel(cfg.vault, item.path): item for item in here
                  if item.note_type == "source" and item.meta.get("primary_category_id") == cid}
        if direct:
            L += ["## 本主题全部来源 / All sources in this topic", ""]
            L += [reading._catalog_entry(cfg.vault, direct[path]) for path in sorted(direct)]
            L.append("")
        pend = [n for n in here if rel(cfg.vault, n.path).startswith("80_queues/")][:5]
        if pend:
            L.append("## 待处理 / Open items")
            L += [f"- ⚠️ [[{rel(cfg.vault, n.path)}]]" for n in pend]
            L.append("")
        if node["level"] in (1, 3):
            L.append(f"→ 本域地图: [[{d}/_map|{node['title']} map]]")
        else:
            root = registry.path_of(cid)[0]
            L.append(f"→ 所属领域地图: [[{node_dir(registry, root['category_id'])}/_map|"
                     f"{root['title']} map]]")
        out[f"{d}/_index.md"] = _fm(node["title"], f"Sub-Home for {node['title']}",
                                   f'knowledge_parent: "[[{parent}]]"\n') + "\n".join(L) + "\n"
    return out


# ---- maps ------------------------------------------------------------------------------
def build_global_atlas(cfg: KFConfig, registry: TaxonomyRegistry) -> dict:
    l1s = sorted(registry.active(level=1), key=lambda n: n["title"])
    nodes_shown = 0
    L = ["# 🗺 Global Atlas", "", brain.navigation(registry, None), "", "```mermaid", "graph LR"]
    outline = ["", "## Outline", ""]
    for i, l1 in enumerate(l1s):
        if nodes_shown >= MAX_ATLAS_NODES:
            break
        nid = f"d{i}"
        L.append(f'  {nid}["{l1["title"][:24]}"]')
        nodes_shown += 1
        outline.append(f"- [[{node_dir(registry, l1['category_id'])}/_index|{l1['title']}]]")
        for j, l2 in enumerate(sorted(registry.children(l1["category_id"]),
                                      key=lambda n: n["title"])):
            if nodes_shown >= MAX_ATLAS_NODES:
                break
            cid2 = f"d{i}_{j}"
            L.append(f'  {cid2}("{l2["title"][:24]}")')
            L.append(f"  {nid} --> {cid2}")
            nodes_shown += 1
            outline.append(f"  - [[{node_dir(registry, l2['category_id'])}/_index|{l2['title']}]]")
    L.append("```")
    content = (_fm("Global Atlas", f"L1/L2 overview (≤{MAX_ATLAS_NODES} nodes)")
               + "\n".join(L + outline) + "\n")
    return {"40_maps/_Global Atlas.md": content}


def build_domain_map(cfg: KFConfig, vi: VaultIndex, registry: TaxonomyRegistry,
                     l1_id: str) -> dict:
    node = registry.get(l1_id)
    if not node:
        return {}
    by_cat = _notes_by_category(vi)
    L = [f"# 🗺 {node['title']} — Domain Map", "", brain.navigation(registry, l1_id), ""]

    def walk(cid: str, depth: int):
        for k in sorted(registry.children(cid), key=lambda n: n["title"]):
            L.append("  " * depth
                     + f"- [[{node_dir(registry, k['category_id'])}/_index|{k['title']}]]")
            concepts = [n for n in by_cat.get(k["category_id"], [])
                        if n.note_type == "concept"][:3]
            for c in concepts:
                L.append("  " * (depth + 1)
                         + f"- 💡 [[{rel(cfg.vault, c.path)}|{c.meta.get('title', c.path.stem)}]]")
            walk(k["category_id"], depth + 1)

    walk(l1_id, 0)
    if len(L) == 4:
        L.append("_(no subcategories yet)_")
    d = node_dir(registry, l1_id)
    return {f"{d}/_map.md": _fm(f"{node['title']} map", "Domain map") + "\n".join(L) + "\n"}


def build_topic_map(cfg: KFConfig, vi: VaultIndex, registry: TaxonomyRegistry,
                    topic_id: str) -> dict:
    node = registry.get(topic_id)
    if not node:
        return {}
    by_cat = _notes_by_category(vi)
    L = [f"# {node['title']} — Topic Map", "", brain.navigation(registry, topic_id), ""]
    kids = registry.children(topic_id)
    if kids:
        L.append("## Subtopics")
        L += [f"- [[{node_dir(registry, k['category_id'])}/_index|{k['title']}]]" for k in kids]
    concepts = [n for n in by_cat.get(topic_id, []) if n.note_type in ("concept", "entity")][:10]
    if concepts:
        L.append("## Core pages")
        L += [f"- [[{rel(cfg.vault, n.path)}|{n.meta.get('title', n.path.stem)}]]"
              for n in concepts]
    d = node_dir(registry, topic_id)
    return {f"{d}/_map.md": _fm(f"{node['title']} topic map", "Topic map") + "\n".join(L) + "\n"}


def rebuild_all(cfg: KFConfig, vi: VaultIndex, registry: TaxonomyRegistry,
                briefing_link: Optional[str] = None,
                audio_link: Optional[str] = None) -> dict:
    """Everything HOME/maps in one pass → {vault_rel: content}."""
    files = {}
    files.update(brain.build(cfg.vault, vi, registry))
    files["Library.base"] = library.build()
    files[live_brief.PATH] = live_brief.build(cfg.vault, vi)
    files["Reading Desk.md"] = desk.build(cfg.vault, vi)
    files["Library Index.md"] = reading.catalog(cfg.vault, vi, registry)
    files["Knowledge Map.md"] = reading.overview(cfg.vault, vi, registry)
    activity = cfg.vault / "90_meta/Library Activity.md"
    if not activity.exists():
        files["90_meta/Library Activity.md"] = "# Library Activity\n\n[[HOME|Home]]\n"
    files.update(build_home(cfg, vi, registry, briefing_link=briefing_link,
                            audio_link=audio_link))
    files.update(build_all_domains(cfg, registry))
    files.update(build_subhomes(cfg, vi, registry))
    files.update(build_global_atlas(cfg, registry))
    for l1 in registry.active(level=1):
        files.update(build_domain_map(cfg, vi, registry, l1["category_id"]))
    for l3 in registry.active(level=3):
        files.update(build_topic_map(cfg, vi, registry, l3["category_id"]))
    return files
